function createAllExamForms() {
  Logger.log("=== เริ่มต้นกระบวนการสร้าง Google Forms ข้อสอบปลายภาค 5 รายวิชา ===");
  var results = [];

  for (var code in ALL_EXAM_DATA) {
    var c = ALL_EXAM_DATA[code];
    Logger.log("กำลังสร้างข้อสอบวิชา: [" + c.course_code + "] " + c.course_name + "...");
    
    var formTitle = "ข้อสอบปลายภาค: [" + c.course_code + "] " + c.course_name + " (1/2569)";
    var form = FormApp.create(formTitle);
    
    // ตั้งค่าคำอธิบาย
    var descLines = [
      "แบบทดสอบวัดผลปลายภาคเรียนที่ 1 ปีการศึกษา 2569",
      "วิทยาลัยการอาชีพเบตง แผนกวิชาช่างอิเล็กทรอนิกส์",
      "ระดับชั้น: " + c.level + " | เวลาสอบ: " + c.time_minutes + " นาที | คะแนนเต็ม: 40 คะแนน",
      "ผู้สอน: " + (c.instructor || "นายณัฐชา ไชยหมาน"),
      "",
      "คำชี้แจง:",
      "- ตอนที่ 1: แบบทดสอบปรนัย 4 ตัวเลือก จำนวน 35 ข้อ (30 คะแนน)",
      "- ตอนที่ 2: แบบทดสอบอัตนัย/เขียนตอบ จำนวน 3 ข้อ (10 คะแนน)"
    ];
    form.setDescription(descLines.join("\n"));

    // เปิดโหมด Quiz (ตั้งค่าเฉลยและให้คะแนน)
    form.setIsQuiz(true);
    form.setRequireLogin(false);
    form.setShowLinkToRespondAgain(false);

    // ข้อมูลผู้เข้าสอบ
    var itemStudentId = form.addTextItem();
    itemStudentId.setTitle("รหัสนักศึกษา").setRequired(true);

    var itemStudentName = form.addTextItem();
    itemStudentName.setTitle("ชื่อ - นามสกุล").setRequired(true);

    var itemStudentLevel = form.addTextItem();
    itemStudentLevel.setTitle("ระดับชั้น / กลุ่มเรียน").setRequired(true);

    // ================= ตอนที่ 1: ปรนัย =================
    form.addPageBreakItem()
      .setTitle("ตอนที่ 1: แบบทดสอบปรนัย 4 ตัวเลือก (35 ข้อ รวม 30 คะแนน)")
      .setHelpText("ให้นักเรียนนักศึกษาเลือกคำตอบที่ถูกต้องที่สุดเพียงข้อเดียว");

    var mcList = c.multiple_choice || [];
    for (var i = 0; i < mcList.length; i++) {
      var q = mcList[i];
      var mcItem = form.addMultipleChoiceItem();
      mcItem.setTitle("ข้อที่ " + (i + 1) + ". " + q.question)
            .setRequired(true)
            .setPoints(1); // 1 คะแนนต่อข้อ (รวม 35 ข้อ คิดสัดส่วนเป็น 30 คะแนน)

      var choices = [];
      for (var j = 0; j < q.choices.length; j++) {
        var ch = q.choices[j];
        var isCorrect = (ch.key === q.correct_answer);
        var label = ch.key + ". " + ch.text;
        choices.push(mcItem.createChoice(label, isCorrect));
      }
      mcItem.setChoices(choices);

      // ตั้งค่าเฉลยและคำอธิบาย
      if (q.explanation) {
        var feedback = FormApp.createFeedback()
          .setText("คำอธิบายเฉลย: " + q.explanation)
          .build();
        mcItem.setFeedbackForCorrect(feedback);
        mcItem.setFeedbackForIncorrect(feedback);
      }
    }

    // ================= ตอนที่ 2: อัตนัย =================
    form.addPageBreakItem()
      .setTitle("ตอนที่ 2: แบบทดสอบอัตนัย / เชิงปฏิบัติและวิเคราะห์ (3 ข้อ รวม 10 คะแนน)")
      .setHelpText("ให้นักเรียนนักศึกษาพิมพ์คำอธิบาย หรือเขียนโค้ดโปรแกรมตามที่โจทย์กำหนด");

    var subList = c.subjective || [];
    for (var k = 0; k < subList.length; k++) {
      var sub = subList[k];
      var pItem = form.addParagraphTextItem();
      pItem.setTitle("ข้ออัตนัยที่ " + (k + 1) + " [" + (sub.category || "ข้อเขียน") + "]: " + sub.question)
           .setRequired(true)
           .setPoints(k === 2 ? 4 : 3); // 3, 3, 4 คะแนน รวม 10 คะแนน
      
      if (sub.solution) {
        pItem.setHelpText("เกณฑ์และแนวคำตอบ:\n" + sub.solution);
      }
    }

    results.push({
      code: c.course_code,
      name: c.course_name,
      editUrl: form.getEditUrl(),
      publishedUrl: form.getPublishedUrl()
    });

    Logger.log("  -> สร้างสำเร็จ! ลิงก์สำหรับส่งให้นักเรียน: " + form.getPublishedUrl());
  }

  Logger.log("===============================================================");
  Logger.log("🎉 สร้าง Google Forms เสร็จสมบูรณ์ครบทั้ง 5 รายวิชา!");
  Logger.log("===============================================================");
  for (var r = 0; r < results.length; r++) {
    Logger.log("[" + results[r].code + "] " + results[r].name);
    Logger.log("  - ลิงก์ให้นักเรียนทำข้อสอบ (Published URL): " + results[r].publishedUrl);
    Logger.log("  - ลิงก์สำหรับแก้ไข/ดูผลสอบ (Edit URL): " + results[r].editUrl);
  }
}
